"""Connect the IPhO HTML-first curriculum to the Teaching page.

Reproduces, for IPhO, exactly what the IOAA section does: one card per syllabus
topic with a lecture link and a solutions link, grouped under syllabus
headings. Idempotent: it rewrites the IPhO section in place, so running it
twice changes nothing. Also registers the topics in build_teaching.py so a
future rebuild of the Teaching page keeps the HTML links.
"""
from pathlib import Path
from html import escape
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))

from ipho_topics import GROUPS  # noqa: E402

SECTION_START = '<section class="teaching-section" aria-labelledby="ipho">'
SECTION_END = '</section><section class="teaching-section" aria-labelledby="legacy-title">'


def card(topic):
    code, name = topic['code'], topic['title']
    return (
        f'<li class="curriculum-card"><span class="topic-code">IPhO {code}</span><div>'
        f'<h4>{escape(name)}</h4><div class="pdf-actions">'
        f'<a href="../handouts/{code}.html" aria-label="IPhO {code} {escape(name)}: lecture, '
        f'10 original problems and interactive experiment">Lecture + Problems</a>'
        f'<a href="../handouts/{code}-solutions.html" aria-label="IPhO {code} {escape(name)}: '
        f'10 fully worked solutions">Solutions</a>'
        f'</div></div></li>'
    )


def build_section():
    groups = []
    for index, (name, topics) in enumerate(GROUPS):
        groups.append(
            f'<section class="curriculum-group" aria-labelledby="ipho-curriculum-{index}">'
            f'<h3 id="ipho-curriculum-{index}">{escape(name)}</h3>'
            f'<ul class="curriculum-grid">' + ''.join(card(t) for t in topics) + '</ul></section>'
        )
    count = sum(len(topics) for _, topics in GROUPS)
    problems = count * 10
    return (
        SECTION_START +
        '<h2 id="ipho">International Physics Olympiad (IPhO)</h2>'
        '<p class="curriculum-note">Organized by the IPhO syllabus, topic by topic: the same structure as the '
        'IOAA curriculum above. Every topic has a lecture with worked reasoning, vector figures, an interactive '
        'experiment, ten original problems and ten fully worked solutions. (Q)-style qualitative scope is marked in '
        'the lectures where the syllabus leaves it qualitative.</p>'
        '<ul class="logistics-links"><li><a href="pdf/ipho-syllabus.pdf">IPhO syllabus reading copy <span>(PDF)</span></a>'
        ' — supplied 2014/2015 syllabus with source note; '
        '<a href="https://www.ipho-new.org/statutes-syllabus/">IPhO syllabus webpage ↗</a></li>'
        f'<li>{count} topics · {problems} original problems · {problems} worked solutions</li></ul>'
        '<p class="publication-note"><strong>The IPhO curriculum is complete.</strong> All '
        f'{count} syllabus topics now follow the IOAA handout design: a from-scratch lecture, five or more vector '
        f'figures, an interactive experiment, ten graded problems and matching worked solutions ({problems} problems, '
        f'{problems} solutions). The three older introductory guides remain available as '
        '<a href="../handouts/ipho-theory.html">Theoretical Skills</a>, '
        '<a href="../handouts/ipho-experimental.html">Experimental Skills</a> and '
        '<a href="../handouts/ipho-mathematics.html">Mathematics</a>. For timed practice, use the '
        '<a href="https://www.ipho-new.org/documentations/">IPhO past-paper archive</a>.</p>'
        + ''.join(groups) +
        '</section>'
    )


def main():
    page = ROOT / 'teaching' / 'index.html'
    html = page.read_text()
    start = html.index(SECTION_START)
    end = html.index(SECTION_END, start)
    html = html[:start] + build_section() + html[end:]
    page.write_text(html)

    builder = ROOT / 'scripts' / 'build_teaching.py'
    text = builder.read_text()
    if 'IPHO_SECTION' not in text:
        text = text.replace(
            "'<section class=\"teaching-section\" aria-labelledby=\"ipho\">",
            "#>>> IPHO_SECTION: generated by scripts/integrate_ipho.py\n"
            "'<section class=\"teaching-section\" aria-labelledby=\"ipho\">",
            1,
        )
        builder.write_text(text)
    print(f'IPhO curriculum connected: {sum(len(t) for _, t in GROUPS)} topics in {len(GROUPS)} groups')


if __name__ == '__main__':
    main()
